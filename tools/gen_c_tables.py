"""Write c/src/ldpc_tables.h from ft8nn/data/ldpc.npz (the same tables the Python decoder uses).

    uv run python tools/gen_c_tables.py
"""
from pathlib import Path

import numpy as np

root = Path(__file__).resolve().parents[1]
t = np.load(root / "ft8nn/data/ldpc.npz")


def arr(name, a, ctype):
    rows = ",\n".join("  {" + ",".join(str(int(v)) for v in r) + "}" for r in a)
    return f"static const {ctype} {name}[{a.shape[0]}][{a.shape[1]}] = {{\n{rows}\n}};\n"


out = ["/* Generated by tools/gen_c_tables.py from ft8nn/data/ldpc.npz. Do not edit. */",
       "#pragma once", "#include <stdint.h>", "",
       "/* parity = GEN @ a91 (mod 2) */", arr("LDPC_GEN", t["gen"], "uint8_t"),
       "/* check m -> its bit indices (-1 padded) */", arr("LDPC_NM", t["Nm"], "int16_t"),
       "/* bit n -> its 3 checks */", arr("LDPC_MN", t["Mn"], "int16_t")]
(root / "c/src/ldpc_tables.h").write_text("\n".join(out))
print("wrote c/src/ldpc_tables.h")
