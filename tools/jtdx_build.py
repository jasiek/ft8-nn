#!/usr/bin/env python3
"""Build JTDX's FT8 decoder plus tools/jtdx_ft8_file.f90 (its missing file mode).

    python3 tools/jtdx_build.py [--src third_party/jtdx] [--jobs 8]

Clones JTDX if needed, then builds only what the decoder needs: the Fortran
library (wsjt_FSRCS), the Reed-Solomon/CRC C and C++ (wsjt_CSRCS, ka9q_CSRCS,
wsjt_CXXSRCS) and our driver.  jtdxjt9's own front end (lib/jt9.f90, jt9a.f90,
ipcomm.cpp) is left out, which is why no Qt, hamlib or libusb is needed - only
gfortran, a C/C++ compiler, cmake and FFTW3 single precision.

Source lists are parsed out of JTDX's CMakeLists.txt so they stay in step with
whatever revision is checked out.  Two upstream files need help from a modern
toolchain, neither on the FT8 path:

  * lib/{char,int}.h declare the RS codec with prototypes that disagree with
    the definitions in lib/ftrsd/*.c (int vs unsigned, and DECODE_RS's
    calc_syn argument).  clang 15+ and gcc 14+ reject that, so we generate
    corrected copies into compat/ and put it first on the include path.
  * lib/jplsubs.f (JPL ephemeris, for the astro window) calls its own SPLIT,
    which gfortran 14+ resolves to the F2023 intrinsic.  It is dropped; the
    link proves nothing in the FT8 path refers to it.
"""
import argparse, os, re, subprocess, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JTDX_GIT = "git://git.code.sf.net/p/jtdx/code"

RS_OLD = """void ENCODE_RS(void *p,DTYPE *data,DTYPE *parity);
int DECODE_RS(void *p,DTYPE *data,int *eras_pos,int no_eras);
void *INIT_RS(int symsize,int gfpoly,int fcr,
%sint prim,int nroots,int pad);
void FREE_RS(void *p);"""
RS_NEW = """/* ft8-nn: prototypes corrected to match lib/ftrsd/*.c, which clang 15+ and
   gcc 14+ reject as conflicting types in the original. */
void ENCODE_RS(void *p,DTYPE *data,DTYPE *parity);
int DECODE_RS(void *p,DTYPE *data,int *eras_pos,int no_eras,int calc_syn);
void *INIT_RS(unsigned int symsize,unsigned int gfpoly,unsigned fcr,
		   unsigned prim,unsigned int nroots);
void FREE_RS(void *p);"""


def cmake_list(text, name):
    m = re.search(r"^set \(%s\s*\n(.*?)^\s*\)\s*$" % name, text, re.S | re.M)
    if not m:
        sys.exit(f"jtdx_build: {name} not found in JTDX CMakeLists.txt")
    out = []
    for line in m.group(1).splitlines():
        line = line.split("#")[0].strip()
        if line and not line.startswith("${"):
            out.append(line)
    return out


def write_compat(src, build):
    """Corrected copies of char.h / int.h (JTDX builds with -DBIGSYM=1 -> int.h)."""
    compat = os.path.join(build, "compat")
    os.makedirs(compat, exist_ok=True)
    for header in ("char.h", "int.h"):
        text = open(os.path.join(src, "lib", header)).read()
        for indent in ("\t\t    ", "\t\t   ", "\t\t"):
            old = RS_OLD % indent
            if old in text:
                text = text.replace(old, RS_NEW)
                break
        else:
            sys.exit(f"jtdx_build: RS prototypes in lib/{header} are not the "
                     "expected ones; check the JTDX revision")
        open(os.path.join(compat, header), "w").write(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.path.join(REPO, "third_party", "jtdx"))
    ap.add_argument("--build", default=None)
    ap.add_argument("--jobs", type=int, default=8)
    a = ap.parse_args()
    src = os.path.abspath(a.src)
    build = os.path.abspath(a.build or os.path.join(src, "..", "jtdx-build"))

    if not os.path.isdir(src):
        os.makedirs(os.path.dirname(src), exist_ok=True)
        print(f"cloning JTDX into {src}", flush=True)
        subprocess.run(["git", "clone", "--depth", "1", JTDX_GIT, src], check=True)
    rev = subprocess.run(["git", "-C", src, "log", "-1", "--format=%h %ad"],
                         capture_output=True, text=True).stdout.strip()
    print(f"JTDX source: {src} ({rev})")

    text = open(os.path.join(src, "CMakeLists.txt")).read()
    fsrcs = [f for f in cmake_list(text, "wsjt_FSRCS") if f != "lib/jplsubs.f"]
    csrcs = cmake_list(text, "ka9q_CSRCS") + cmake_list(text, "wsjt_CSRCS")
    xsrcs = cmake_list(text, "wsjt_CXXSRCS")
    print(f"sources: {len(fsrcs)} Fortran, {len(csrcs)} C, {len(xsrcs)} C++")

    os.makedirs(build, exist_ok=True)
    write_compat(src, build)
    block = lambda items: "\n".join(f"  {src}/{i}" for i in items)
    open(os.path.join(build, "CMakeLists.txt"), "w").write(f"""\
# Generated by tools/jtdx_build.py - do not edit.
cmake_minimum_required (VERSION 3.20)
project (jtdx_ft8_file C CXX Fortran)
set (CMAKE_BUILD_TYPE Release CACHE STRING "")

# JTDX's own flags: CMakeLists.txt General_FFLAGS, gfortran release, line 934
set (CMAKE_Fortran_FLAGS "${{CMAKE_Fortran_FLAGS}} -Wall -Wno-conversion \
-fno-second-underscore -fopenmp -std=legacy")
set (CMAKE_Fortran_FLAGS_RELEASE "-O3 -fbounds-check -funroll-all-loops -fno-f2c")
set (CMAKE_CXX_FLAGS "${{CMAKE_CXX_FLAGS}} -std=gnu++11")
add_definitions (-DCMAKE_BUILD -DBIGSYM=1 -DUNIX)

find_package (PkgConfig REQUIRED)
pkg_check_modules (FFTW3F REQUIRED fftw3f)
include_directories (${{CMAKE_CURRENT_SOURCE_DIR}}/compat ${{FFTW3F_INCLUDE_DIRS}}
  /opt/homebrew/include /usr/local/include {src}/lib)
link_directories (${{FFTW3F_LIBRARY_DIRS}})

add_library (wsjt_cxx STATIC
{block(csrcs)}
{block(xsrcs)}
  )
add_library (wsjt_fort_omp STATIC
{block(fsrcs)}
  )
set_target_properties (wsjt_fort_omp PROPERTIES
  Fortran_MODULE_DIRECTORY ${{CMAKE_BINARY_DIR}}/fortran_modules_omp)

add_executable (jtdx_ft8_file {REPO}/tools/jtdx_ft8_file.f90)
set_target_properties (jtdx_ft8_file PROPERTIES
  Fortran_MODULE_DIRECTORY ${{CMAKE_BINARY_DIR}}/fortran_modules_omp)
target_link_libraries (jtdx_ft8_file wsjt_fort_omp wsjt_cxx
  ${{FFTW3F_LIBRARIES}} fftw3f_threads gomp)
""")

    out = os.path.join(build, "build")
    subprocess.run(["cmake", "-S", build, "-B", out], check=True)
    subprocess.run(["cmake", "--build", out, "-j", str(a.jobs)], check=True)
    exe = os.path.join(out, "jtdx_ft8_file")
    print(f"\nbuilt {exe}")


if __name__ == "__main__":
    main()
