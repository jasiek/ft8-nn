"""Write the amateur call-sign blocks in use: ft8nn/data/call_blocks.txt and c/src/call_blocks.h.

  python3 tools/gen_call_blocks.py [path/to/cty.dat]   (default: WSJT-X's copy on macOS)

Only the leading one or two characters of the prefixes in a country file are kept: a call is plausible when its first
character is a whole block (K, W, ...) or its first two characters are a block in use (AA, E2, 3B, ...). That is the
ITU allocation in coarse form, not the country file's content. Used by decoder.plausible() for OSD-family decodes.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
cty = sys.argv[1] if len(sys.argv) > 1 else "/Applications/wsjtx.app/Contents/Resources/wsjtx/cty.dat"
CALL = re.compile(r"^[A-Z0-9]{1,3}[0-9][A-Z0-9]{0,4}$")
pre, exact = set(), set()
for line in open(cty, encoding="latin-1"):
    if line.startswith(" "):  # continuation lines hold the prefix lists; entity header lines don't start with a space
        for tok in line.strip().rstrip(";").split(","):
            tok = re.sub(r"[\(\[<{~].*$", "", tok.strip())
            if tok:
                (exact if tok.startswith("=") else pre).add(tok.lstrip("="))
one = sorted(p for p in pre if len(p) == 1)
two = sorted({p[:2] for p in pre if len(p) >= 2} | {e[:2] for e in exact if CALL.match(e)})
two = [t for t in two if t[0] not in one]  # covered by a one-character block anyway

(ROOT / "ft8nn/data/call_blocks.txt").write_text(
    "# amateur call-sign blocks in use (tools/gen_call_blocks.py): line 1 one-character blocks, line 2 two-character\n"
    + "".join(one) + "\n" + " ".join(two) + "\n")
h = ["/* Generated by tools/gen_call_blocks.py. Do not edit. Amateur call-sign blocks in use. */",
     f'static const char CALL_BLOCKS1[] = "{"".join(one)}";',
     f"#define N_CALL_BLOCKS2 {len(two)}",
     "static const char CALL_BLOCKS2[N_CALL_BLOCKS2][3] = {"]
for i in range(0, len(two), 16):
    h.append("    " + ", ".join(f'"{t}"' for t in two[i:i + 16]) + ",")
h.append("};")
(ROOT / "c/src/call_blocks.h").write_text("\n".join(h) + "\n")
print(f"{len(one)} one-character blocks ({''.join(one)}), {len(two)} two-character blocks")
